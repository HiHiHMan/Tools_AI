/* =====================================================
   FAVICON
===================================================== */

function getDomain(url) {

    if (!url || url === "#") {
        return null;
    }

    try {

        return new URL(url).hostname;

    } catch {

        return null;

    }

}


function getFavicon(url) {

    const domain = getDomain(url);

    if (!domain) {
        return null;
    }

    return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;

}


/* =====================================================
   FALLBACK ICON
===================================================== */

function getInitials(name) {

    const words = name
        .replace(/[^a-zA-Z0-9ก-๙ ]/g, "")
        .split(" ")
        .filter(Boolean);

    if (words.length === 1) {

        return words[0]
            .substring(0, 2)
            .toUpperCase();

    }

    return (
        words[0][0] +
        words[1][0]
    ).toUpperCase();

}


/* =====================================================
   RENDER
===================================================== */

const categoriesContainer =
    document.getElementById("categories");


function renderCategories(
    filter = "all",
    keyword = ""
) {

    categoriesContainer.innerHTML = "";

    const grouped = {};

    tools.forEach(tool => {

        if (!grouped[tool.category]) {
            grouped[tool.category] = [];
        }

        grouped[tool.category].push(tool);

    });
    


    Object.keys(grouped).sort((a, b) => Number(a) - Number(b)).forEach(category => {

        if (
            filter !== "all" &&
            filter !== category
        ) {
            return;
        }


        const filteredTools =
            grouped[category].filter(tool => {

                const search =
                    keyword.toLowerCase();

                return (
                    tool.name
                        .toLowerCase()
                        .includes(search) ||

                    tool.type
                        .toLowerCase()
                        .includes(search)
                );

            });


        if (!filteredTools.length) {
            return;
        }


        const section =
            document.createElement("section");

        section.className =
            "category reveal";


        section.dataset.category =
            category;


        section.innerHTML = `

            <div class="category-header">

                <div class="category-number">
                    ${category}
                </div>

                <div class="category-name">
                    ${categoryNames[category]}
                </div>

                <div class="category-type">
                    ${filteredTools.length} tools
                </div>

            </div>

            <div class="tools"></div>

        `;


        const toolsContainer =
            section.querySelector(".tools");


        filteredTools.forEach(
            (tool, index) => {

                const favicon =
                    getFavicon(tool.url);

                const initials =
                    getInitials(tool.name);


                const article =
                    document.createElement("a");

                article.className =
                    "tool";

                article.href =
                    tool.url;

                if (tool.url !== "#") {

                    article.target = "_blank";

                    article.rel =
                        "noopener noreferrer";

                }


                article.dataset.name =
                    tool.name.toLowerCase();


                article.innerHTML = `

                    <div class="tool-index">
                        ${String(index + 1).padStart(2, "0")}
                    </div>

                    <div class="tool-icon">

                        ${
                            favicon
                            ?
                            `
                            <img
                                src="${favicon}"
                                alt="${tool.name}"
                                loading="lazy"
                                onerror="
                                    this.style.display='none';
                                    this.nextElementSibling.style.display='flex';
                                "
                            >
                            `
                            :
                            ""
                        }

                        <span
                            class="fallback"
                            style="
                                display:${favicon ? "none" : "flex"};
                                align-items:center;
                                justify-content:center;
                                width:100%;
                                height:100%;
                            "
                        >
                            ${initials}
                        </span>

                    </div>

                    <div class="tool-name">
                        ${tool.name}
                    </div>

                    <div class="tool-description">
                        ${tool.type}
                    </div>

                    <div class="tool-arrow">
                        ↗
                    </div>

                `;


                toolsContainer.appendChild(
                    article
                );

            }
        );


        categoriesContainer.appendChild(
            section
        );

    });


    observeReveals();

}


